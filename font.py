def render_text(text, spacing=1):
    """Return a 7-row grid (list of strings) for text, letters separated by `spacing` blank columns."""
    rows = [""] * 7
    chars = list(text.upper())
    for i, ch in enumerate(chars):
        if ch not in GLYPHS:
            raise ValueError(f"No glyph for {ch!r}. Supported: {''.join(sorted(GLYPHS))}")
        g = GLYPHS[ch]
        for r in range(7):
            rows[r] += g[r]
            if i < len(chars) - 1:
                rows[r] += "." * spacing
    return rows


# Icons: '.' off, '1'-'4' brightness (4 = full), '#' = 4.
ICONS = {
    "poop": ["...4.1", "..44..", ".4444.", ".2222.", "444444", "222222", "444444"],
}


def compose(text, icon=None, gap=1, spacing=1):
    """Grid of brightness chars ('.', '1'-'4'): optional icon, gap, then text."""
    rows = [r.replace("#", "4") for r in render_text(text, spacing)]
    if icon:
        ic = ICONS[icon]
        rows = [ic[r].replace("#", "4") + "." * gap + rows[r] for r in range(7)]
    return rows


